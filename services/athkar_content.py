def get_athkar_pool(athkar_type: str = "mixed") -> list[str]:
    if athkar_type == "mixed":
        all_athkar = []
        for pool in ATHKAR_POOL.values():
            all_athkar.extend(pool)
        return all_athkar
    return ATHKAR_POOL.get(athkar_type, ATHKAR_POOL.get("mixed", []))


def get_random_athkar(athkar_type: str = "mixed") -> str:
    pool = get_athkar_pool(athkar_type)
    if not pool:
        return "سبحان الله وبحمده"
    return random.choice(pool)


def format_athkar_schedule_value(mode: str, interval_minutes: int = None, daily_goal: int = None) -> str:
    if mode == "interval":
        return f"Every {interval_minutes} min" if interval_minutes else "Not set"
    elif mode == "goal":
        return f"{daily_goal}/day" if daily_goal else "Not set"
    return "Not set"